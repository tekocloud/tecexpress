import { expect, test } from '@playwright/test'

test('scheduler edits appointments, navigates with the keyboard and preserves parent models', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#scheduler')
  const scheduler = page.getByRole('region', { name: 'Teamkalender', exact: true })
  await expect(scheduler.locator('.tx-scheduler-day-column')).toHaveCount(7)
  const review = scheduler.getByRole('button', { name: /^Projektbesprechung,/ })
  const customer = scheduler.getByRole('button', { name: /^Kundengespräch,/ })
  const first = await review.boundingBox(), second = await customer.boundingBox()
  expect(first).not.toBeNull(); expect(second).not.toBeNull()
  expect(first!.x + first!.width).toBeLessThanOrEqual(second!.x)
  const cell = scheduler.locator('[data-day="0"][data-slot="0"]')
  await cell.focus()
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowDown')
  await expect(scheduler.locator('[data-day="1"][data-slot="1"]')).toBeFocused()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Termin anlegen' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('Beginn', { exact: true })).toHaveValue('2026-10-20T08:30')
  await dialog.getByLabel('Titel', { exact: true }).fill('Integrationstermin')
  await dialog.getByLabel('Beschreibung', { exact: true }).fill('Aus dem Browsertest')
  await dialog.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('#scheduler > .action-log')).toContainText('8 Termine')
  await scheduler.getByRole('button', { name: /^Integrationstermin,/ }).click()
  const edit = page.getByRole('dialog', { name: 'Termin bearbeiten' })
  await expect(edit.getByLabel('Beschreibung', { exact: true })).toHaveValue('Aus dem Browsertest')
  await edit.getByLabel('Titel', { exact: true }).fill('Überarbeiteter Termin')
  await edit.getByLabel('Ende', { exact: true }).fill('2026-10-20T08:00')
  await edit.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(edit.getByRole('alert')).toContainText('nach dem Beginn')
  await edit.getByLabel('Ende', { exact: true }).fill('2026-10-20T09:30')
  await edit.getByRole('button', { name: 'Speichern', exact: true }).click()
  await scheduler.getByRole('button', { name: /^Überarbeiteter Termin,/ }).click()
  await edit.getByRole('button', { name: 'Termin löschen', exact: true }).click()
  await expect(edit.getByRole('alert')).toContainText('endgültig löschen?')
  await edit.getByRole('button', { name: 'Endgültig löschen', exact: true }).click()
  await expect(scheduler.getByRole('button', { name: /^Überarbeiteter Termin,/ })).toHaveCount(0)
  await expect(page.locator('#scheduler > .action-log')).toContainText('7 Termine')
  await page.getByRole('switch', { name: 'Nur lesen', exact: true }).check()
  await expect(scheduler.getByRole('button', { name: '＋ Neuer Termin', exact: true })).toHaveCount(0)
  await review.click()
  const details = page.getByRole('dialog', { name: 'Termindetails' })
  await expect(details.getByLabel('Titel', { exact: true })).toHaveAttribute('readonly')
  await expect(details.getByRole('button', { name: 'Speichern', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await scheduler.getByRole('button', { name: 'Monat', exact: true }).click()
  await expect(scheduler.locator('.tx-scheduler-month-day')).toHaveCount(42)
  await scheduler.getByLabel('Kalenderdatum', { exact: true }).fill('2027-01-01')
  await expect(scheduler.locator('.tx-scheduler-period')).toContainText('Januar 2027')
  await scheduler.getByRole('button', { name: 'Vorheriger Zeitraum' }).click()
  await expect(scheduler.locator('.tx-scheduler-period')).toContainText('Dezember 2026')
  expect(errors).toEqual([])
})

for (const theme of ['light', 'dark']) {
  test(`scheduler ${theme}: desktop, month, mobile and all-day editor`, async ({ page }, testInfo) => {
    await page.addInitScript(value => localStorage.setItem('tx-demo-theme', value), theme)
    await page.setViewportSize({ width: 1440, height: 1100 })
    await page.goto('/#scheduler')
    const scheduler = page.getByRole('region', { name: 'Teamkalender', exact: true })
    await scheduler.screenshot({ path: testInfo.outputPath(`scheduler-${theme}-week.png`) })
    await scheduler.getByRole('button', { name: 'Monat', exact: true }).click()
    await expect(scheduler.locator('.tx-scheduler-month-day')).toHaveCount(42)
    await scheduler.screenshot({ path: testInfo.outputPath(`scheduler-${theme}-month.png`) })
    await scheduler.locator('.tx-scheduler-month-day').filter({ has: page.getByRole('button', { name: /^Release-Tag,/ }) }).getByRole('button', { name: /^Ganztagstermin erstellen:/ }).click()
    const dialog = page.getByRole('dialog', { name: 'Termin anlegen' })
    await expect(dialog.getByLabel('Ganztägig', { exact: true })).toBeChecked()
    await expect(dialog.getByLabel('Beginn', { exact: true })).toHaveValue('2026-10-22')
    await expect(dialog.getByLabel('Ende (exklusiv)', { exact: true })).toHaveValue('2026-10-23')
    await dialog.getByLabel('Titel', { exact: true }).fill('Ganztagsplanung')
    await dialog.getByRole('button', { name: 'Speichern', exact: true }).click()
    await expect(scheduler.getByRole('button', { name: /^Ganztagsplanung,/ })).toHaveCount(1)
    await scheduler.getByRole('button', { name: 'Tag', exact: true }).click()
    await expect(scheduler.locator('.tx-scheduler-day-column')).toHaveCount(1)
    await page.setViewportSize({ width: 390, height: 844 })
    await scheduler.scrollIntoViewIfNeeded()
    await scheduler.screenshot({ path: testInfo.outputPath(`scheduler-${theme}-mobile.png`) })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await scheduler.getByRole('button', { name: '＋ Neuer Termin', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath(`scheduler-${theme}-form-mobile.png`) })
  })
}

test('calendar days follow Europe/Berlin daylight saving rather than 24-hour offsets', async ({ browser }) => {
  const context = await browser.newContext({ timezoneId: 'Europe/Berlin' })
  const page = await context.newPage()
  await page.goto('/#scheduler')
  const scheduler = page.getByRole('region', { name: 'Teamkalender', exact: true })
  await scheduler.getByRole('button', { name: 'Tag', exact: true }).click()
  await scheduler.getByLabel('Kalenderdatum').fill('2026-03-28')
  await scheduler.getByRole('button', { name: 'Nächster Zeitraum' }).click()
  await expect(scheduler.getByLabel('Kalenderdatum')).toHaveValue('2026-03-29')
  await scheduler.getByRole('button', { name: 'Nächster Zeitraum' }).click()
  await expect(scheduler.getByLabel('Kalenderdatum')).toHaveValue('2026-03-30')
  await scheduler.getByRole('button', { name: '＋ Neuer Termin', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Titel', { exact: true }).fill('Zeitumstellung')
  await dialog.getByLabel('Beginn', { exact: true }).fill('2026-03-29T02:30')
  await dialog.getByLabel('Ende', { exact: true }).fill('2026-03-29T04:00')
  await dialog.getByRole('button', { name: 'Speichern', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('existiert nicht')
  await context.close()
})
