import { expect, test } from '@playwright/test'

test('CardView searches, pages, selects and activates card actions with the keyboard', async ({ page }) => {
  await page.goto('/#cards')
  const cards = page.getByRole('region', { name: 'Projektkarten', exact: true })
  await expect(cards.locator('.tx-cardview-item')).toHaveCount(3)
  await cards.getByRole('checkbox', { name: 'Karte Kundenportal auswählen', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(cards.locator('.tx-cardview-footer')).toContainText('1 ausgewählt')
  await cards.getByRole('button', { name: 'Nächste Kartenseite', exact: true }).click()
  await expect(cards.getByRole('heading', { name: 'Analytics Hub', exact: true })).toBeVisible()
  await cards.getByRole('searchbox', { name: 'Karten durchsuchen', exact: true }).fill('produkt & design')
  await expect(cards.locator('.tx-cardview-item')).toHaveCount(2)
  await expect(cards.locator('.tx-cardview-footer')).toContainText('Seite 1 / 1')
  await expect(cards.getByRole('checkbox', { name: 'Karte Kundenportal auswählen', exact: true })).toBeChecked()
  await cards.getByRole('button', { name: 'Details: Kundenportal', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.tx-toast')).toContainText('Kundenportal')
  await cards.getByRole('searchbox').fill('nicht vorhanden')
  await expect(cards).toContainText('Keine Karten vorhanden')
})

test('Chat handles typing, newlines, IME, own and incoming messages, read-only and scroll position', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#chat')
  const chat = page.getByRole('region', { name: 'Projektchat', exact: true })
  const input = chat.getByRole('textbox', { name: 'Nachricht', exact: true })
  await expect(chat.locator('.tx-chat-message')).toHaveCount(3)
  await expect(chat.getByRole('button', { name: 'Nachricht senden' })).toBeDisabled()
  await input.fill('Eine Nachricht')
  await page.keyboard.press('Shift+Enter')
  await page.keyboard.type('mit neuer Zeile')
  await expect(input).toHaveValue('Eine Nachricht\nmit neuer Zeile')
  await input.dispatchEvent('compositionstart')
  await page.keyboard.press('Enter')
  await expect(chat.locator('.tx-chat-message')).toHaveCount(3)
  await input.dispatchEvent('compositionend')
  await page.keyboard.press('Enter')
  await expect(chat.locator('.tx-chat-message')).toHaveCount(4)
  await expect(input).toHaveValue('')
  await expect(chat.locator('.tx-chat-own').last()).toContainText('mit neuer Zeile')
  await page.getByRole('switch', { name: 'Schreibanzeige simulieren', exact: true }).check()
  await expect(chat.locator('.tx-chat-typing')).toContainText('Lena Fischer schreibt')
  for (let index = 0; index < 7; index++) {
    await input.fill(`Weitere Nachricht ${index} mit etwas Inhalt für den Verlauf.`)
    await page.keyboard.press('Enter')
  }
  const log = chat.getByRole('log', { name: 'Nachrichtenverlauf' })
  await log.evaluate(element => { element.scrollTop = 0; element.dispatchEvent(new Event('scroll')) })
  await page.getByRole('button', { name: 'Beispielantwort einfügen', exact: true }).click()
  await expect(chat.locator('.tx-chat-unread')).toContainText('1 neue Nachricht')
  expect(await log.evaluate(element => element.scrollTop)).toBe(0)
  await chat.locator('.tx-chat-unread').click()
  await expect(chat.locator('.tx-chat-unread')).toHaveCount(0)
  await expect.poll(() => log.evaluate(element => element.scrollHeight - element.clientHeight - element.scrollTop)).toBeLessThan(48)
  await input.fill('Diesen Entwurf behalten')
  await page.getByRole('switch', { name: 'Chat nur lesen', exact: true }).check()
  await expect(input).toHaveCount(0)
  await page.getByRole('switch', { name: 'Chat nur lesen', exact: true }).uncheck()
  await expect(input).toHaveValue('Diesen Entwurf behalten')
  expect(errors).toEqual([])
})

